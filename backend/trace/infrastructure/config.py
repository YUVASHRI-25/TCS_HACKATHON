"""Load config/detectors.yaml and config/catalogues.yaml, and write generated thresholds."""

from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import yaml

from trace.infrastructure.settings import Settings, get_settings


@dataclass
class TraceConfig:
    detectors: dict[str, Any]
    catalogues: dict[str, Any]

    @property
    def roles(self) -> dict[str, str]:
        return {k: v["role"] for k, v in (self.catalogues.get("signals") or {}).items()}

    @property
    def joining_signals(self) -> set[str]:
        return {k for k, v in (self.catalogues.get("signals") or {}).items() if v.get("joins_network")}

    def validate(self) -> list[str]:
        """Configuration problems that would make scoring ambiguous."""
        problems = []
        weights = self.detectors.get("weights") or {}
        for sig, role in self.roles.items():
            if role == "risk" and sig not in weights:
                problems.append(f"risk signal {sig!r} has no weight in detectors.yaml")
        for tid, t in (self.catalogues.get("typologies") or {}).items():
            for s in t.get("supporting_signals", []):
                if s not in self.roles:
                    problems.append(f"typology {tid} references unknown signal {s!r}")
            for ns in t.get("next_steps", []):
                if ns not in (self.catalogues.get("next_steps") or {}):
                    problems.append(f"typology {tid} references unknown next step {ns!r}")
        return problems


def _load(p: Path) -> dict[str, Any]:
    return yaml.safe_load(p.read_text(encoding="utf-8")) or {}


def load_config(settings: Settings | None = None) -> TraceConfig:
    s = settings or get_settings()
    return TraceConfig(detectors=_load(s.path(s.trace_detectors_path)), catalogues=_load(s.path(s.trace_catalogues_path)))


def thresholds_path(settings: Settings | None = None) -> Path:
    s = settings or get_settings()
    p = s.path(s.trace_detectors_path)
    return p.with_name(p.stem + ".thresholds.yaml")


def write_thresholds(derived: dict[str, Any], settings: Settings | None = None) -> Path:
    path = thresholds_path(settings)
    header = ("# GENERATED by the pipeline from the dataset's own distributions. Do not edit by hand.\n"
              f"# Generated at {datetime.now(timezone.utc).isoformat(timespec='seconds')}\n")
    path.write_text(header + yaml.safe_dump(derived, sort_keys=True), encoding="utf-8")
    return path
