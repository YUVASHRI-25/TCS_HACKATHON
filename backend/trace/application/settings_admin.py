"""Admin-editable detection settings.

Edits go to config/detectors.overrides.yaml (merged over detectors.yaml at load). Only existing keys can be
changed and only to numbers. Thresholds stay data-derived: the admin changes WHICH percentile is used, the
windows/params, weights and tier cut-offs — never a raw threshold value. Changes apply on the next run.
"""

from __future__ import annotations

from copy import deepcopy
from typing import Any

import yaml

from trace.application.accounts import SYSTEM
from trace.data_access.audit.chain import SqlAuditStore
from trace.infrastructure.config import overrides_path, load_config
from trace.infrastructure.settings import Settings

_SECTIONS = ("case_rules", "tiers", "weights", "ml_weights", "penalties")


class SettingsError(ValueError):
    pass


def _num(v: Any) -> bool:
    return isinstance(v, (int, float)) and not isinstance(v, bool)


def editable(settings: Settings) -> dict[str, Any]:
    d = load_config(settings).detectors
    out: dict[str, Any] = {sec: {k: v for k, v in (d.get(sec) or {}).items() if _num(v)} for sec in _SECTIONS}
    out["detectors"] = {}
    for det, spec in (d.get("detectors") or {}).items():
        params = {k: v for k, v in (spec.get("params") or {}).items() if _num(v)}
        derive = {k: {"metric": v["metric"], "percentile": v["percentile"]} for k, v in (spec.get("derive") or {}).items()}
        if params or derive:
            out["detectors"][det] = {"params": params, "derive": derive}
    return out


def apply(settings: Settings, audit: SqlAuditStore, actor: str, patch: dict[str, Any]) -> dict[str, Any]:
    current = editable(settings)
    path = overrides_path(settings)
    over = (yaml.safe_load(path.read_text(encoding="utf-8")) if path.exists() else None) or {}
    changes = []
    for sec in _SECTIONS:
        for k, v in (patch.get(sec) or {}).items():
            if k not in current[sec]:
                raise SettingsError(f"{sec}.{k} is not an editable setting")
            if not _num(v) or v < 0:
                raise SettingsError(f"{sec}.{k} must be a non-negative number")
            if current[sec][k] != v:
                over.setdefault(sec, {})[k] = v
                changes.append({"setting": f"{sec}.{k}", "from": current[sec][k], "to": v})
    for det, spec in (patch.get("detectors") or {}).items():
        if det not in current["detectors"]:
            raise SettingsError(f"detector {det} has no editable settings")
        for k, v in (spec.get("params") or {}).items():
            if k not in current["detectors"][det]["params"] or not _num(v) or v < 0:
                raise SettingsError(f"{det}.params.{k} is not editable or not a non-negative number")
            if current["detectors"][det]["params"][k] != v:
                over.setdefault("detectors", {}).setdefault(det, {}).setdefault("params", {})[k] = v
                changes.append({"setting": f"{det}.{k}", "from": current["detectors"][det]["params"][k], "to": v})
        for k, v in (spec.get("derive") or {}).items():
            if k not in current["detectors"][det]["derive"]:
                raise SettingsError(f"{det}.derive.{k} is not editable")
            pct = v.get("percentile") if isinstance(v, dict) else v
            if not _num(pct) or not 0 < pct < 100:
                raise SettingsError(f"{det}.{k}: percentile must be between 0 and 100")
            if current["detectors"][det]["derive"][k]["percentile"] != pct:
                over.setdefault("detectors", {}).setdefault(det, {}).setdefault("derive", {})[k] = {"percentile": pct}
                changes.append({"setting": f"{det}.{k} percentile",
                                "from": current["detectors"][det]["derive"][k]["percentile"], "to": pct})
    t = {**current["tiers"], **{k: v for k, v in (patch.get("tiers") or {}).items()}}
    if t.get("high", 0) <= t.get("medium", 0):
        raise SettingsError("the HIGH tier cut-off must be above the MEDIUM cut-off")
    if not changes:
        return {"changes": [], "note": "nothing changed"}
    path.write_text("# GENERATED by the admin settings page; merged over detectors.yaml. Audited.\n"
                    + yaml.safe_dump(over, sort_keys=True), encoding="utf-8")
    audit.append(SYSTEM, actor, "update_settings", {"changes": changes})
    return {"changes": changes, "note": "Saved. Run the analysis again to apply the new settings."}


def merge(base: dict[str, Any], over: dict[str, Any]) -> dict[str, Any]:
    out = deepcopy(base)
    for k, v in over.items():
        out[k] = merge(out[k], v) if isinstance(v, dict) and isinstance(out.get(k), dict) else v
    return out
