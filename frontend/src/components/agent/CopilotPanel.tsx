import { useState } from "react";
import { useMutation } from "@tanstack/react-query";
import { Send, Sparkles } from "lucide-react";
import { jsonCall, type CaseOut } from "@/api/client";
import { Badge, Button, Card, ErrorState } from "@/components/ui/primitives";
import { EvidenceChips } from "@/components/evidence/EvidenceChip";

interface Claim { text: string; evidence_ids: string[]; record_ids: string[]; cited: boolean }
interface Answer {
  answer: string; claims: Claim[]; legitimate_explanations: string[]; contradictory_evidence: string[];
  data_limitations: string[]; suggested_next_steps: string[]; rejected_citations: string[]; model: string;
  uncited_claims: number; disclaimer: string;
}

const PROMPTS = [
  "Why is this network suspicious?",
  "Which accounts share the same device?",
  "Show the connected transaction paths.",
  "What evidence supports the leading hypothesis?",
  "What legitimate explanation could exist?",
  "Which suspicious transaction should be examined next?",
  "Explain the risk indicators.",
  "Summarize the investigation.",
  "Re-evaluate the original hypothesis in light of the investigator-recorded facts and describe what changed.",
];

function List({ title, items }: { title: string; items: string[] }) {
  if (!items.length) return null;
  return <div><p className="text-xs font-semibold uppercase tracking-wider text-muted">{title}</p>
    <ul className="mt-1 list-disc space-y-0.5 pl-5 text-sm">{items.map((x, i) => <li key={i}>{x}</li>)}</ul></div>;
}

export function CopilotPanel({ c }: { c: CaseOut }) {
  const [q, setQ] = useState("");
  const ask = useMutation({ mutationFn: (question: string) => jsonCall<Answer>("POST", `/api/cases/${c.id}/copilot`, { question }) });
  const a = ask.data;
  return (
    <div className="space-y-4">
      <Card title={<span className="inline-flex items-center gap-1.5"><Sparkles className="h-3.5 w-3.5" /> Investigation copilot</span>}>
        <p className="mb-2 text-xs text-muted">Answers are generated by the configured LLM from this case's real evidence only. Every claim must cite evidence or link IDs that exist in the case; unknown citations are rejected. If the LLM is unreachable you will see the real error.</p>
        <div className="mb-3 flex flex-wrap gap-1.5">
          {PROMPTS.map((p) => <button key={p} type="button" onClick={() => { setQ(p); ask.mutate(p); }} disabled={ask.isPending}
            className="rounded-full border border-line px-2.5 py-1 text-xs hover:bg-sky-500/10">{p}</button>)}
        </div>
        <form className="flex gap-2" onSubmit={(e) => { e.preventDefault(); if (q.trim().length >= 3) ask.mutate(q.trim()); }}>
          <input value={q} onChange={(e) => setQ(e.target.value)} placeholder="Ask about this investigation…" aria-label="Question"
            className="min-w-0 flex-1 rounded border border-line bg-canvas px-3 py-2 text-sm" />
          <Button type="submit" variant="primary" disabled={ask.isPending || q.trim().length < 3}><Send className="mr-1 inline h-3.5 w-3.5" />Ask</Button>
        </form>
      </Card>
      {ask.isPending && <p className="text-sm text-muted">Asking the LLM with the case context…</p>}
      {ask.isError && <ErrorState error={ask.error} />}
      {a && (
        <Card title="Answer" actions={<Badge tone="blue">{a.model}</Badge>}>
          <div className="space-y-4">
            <p className="whitespace-pre-wrap text-sm leading-relaxed">{a.answer}</p>
            {a.claims.length > 0 && (
              <div><p className="text-xs font-semibold uppercase tracking-wider text-muted">Claims and citations</p>
                <ul className="mt-1 space-y-2">{a.claims.map((cl, i) => (
                  <li key={i} className="rounded border border-line p-2 text-sm">{cl.text}
                    <div className="mt-1 flex flex-wrap items-center gap-1.5">
                      {cl.evidence_ids.some((x) => /^E\d+$/.test(x)) && <EvidenceChips caseId={c.id} ids={cl.evidence_ids.filter((x) => /^E\d+$/.test(x))} />}
                      {[...cl.evidence_ids.filter((x) => !/^E\d+$/.test(x)), ...cl.record_ids].slice(0, 6).map((r) => <span key={r} className="rounded bg-slate-800 px-1.5 py-0.5 font-mono text-[10px]">{r}</span>)}
                      {cl.record_ids.length > 6 && <span className="text-[10px] text-muted">+{cl.record_ids.length - 6} more</span>}
                      {!cl.cited && <Badge tone="amber">no valid citation</Badge>}
                    </div></li>))}</ul></div>
            )}
            <List title="Legitimate explanations" items={a.legitimate_explanations} />
            <List title="Contradictory evidence" items={a.contradictory_evidence} />
            <List title="Data limitations" items={a.data_limitations} />
            <List title="Suggested next steps" items={a.suggested_next_steps} />
            {a.rejected_citations.length > 0 && <p className="text-xs text-amber-300">Rejected {a.rejected_citations.length} citation(s) that do not exist in this case: {a.rejected_citations.slice(0, 5).join(", ")}</p>}
            <p className="text-xs text-muted">{a.disclaimer}</p>
          </div>
        </Card>
      )}
    </div>
  );
}
